#!/usr/bin/env bash
# Спайк механики загрузки: что харнес реально инжектирует в свежую сессию.
#
#   probe-loading.sh list                 перечислить файлы, попавшие в контекст
#   probe-loading.sh dir <каталог>        проверить, грузится ли каталог автоматически
#
# Зачем запускать, а не вспоминать: правила обхода меняются между версиями Claude Code,
# и ошибка здесь опрокидывает всю раскладку — вынесенная «в неавтозагружаемое место»
# деталь может продолжать грузиться, и экономия окажется мнимой.
#
# `dir` создаёт временный файл-маркер, спрашивает свежую сессию, видит ли она его,
# и удаляет маркер в любом случае. Каталог, которого не было, тоже удаляется.
set -euo pipefail

MODE="${1:-}"
case "$MODE" in
  list)
    exec claude -p "Перечисли ТОЛЬКО пути файлов, показанных тебе в контексте под заголовками вида 'Contents of ...'. По одному пути в строке, без комментариев." </dev/null
    ;;
  dir)
    TARGET="${2:?укажи каталог, например rules/reference или references}"
    MARK="PROBE-$(od -An -N4 -tx1 /dev/urandom | tr -d ' \n')"
    CREATED_DIR=""
    [ -d "$TARGET" ] || CREATED_DIR="$TARGET"
    mkdir -p "$TARGET"
    FILE="$TARGET/__probe.md"
    cleanup() {
      rm -f "$FILE"
      [ -n "$CREATED_DIR" ] && rmdir -p "$CREATED_DIR" 2>/dev/null || true
    }
    trap cleanup EXIT
    printf '# %s\nmarker\n' "$MARK" > "$FILE"
    # Сам маркер в вопросе не называется: иначе сессия видит его в своём же промпте
    # и отвечает «да» независимо от того, загружен файл или нет.
    ANSWER=$(claude -p "Не используй инструменты, не читай файлы, отвечай сразу. В твоём контексте может быть показан файл с заголовком вида PROBE-<hex>. Выведи этот заголовок целиком одной строкой, либо NONE, если такого файла в контексте нет." </dev/null 2>&1 | tail -1)
    if [[ "$ANSWER" == *"$MARK"* ]]; then
      echo "AUTO-LOADED: $TARGET грузится в каждую сессию — выносить туда деталь бессмысленно"
    elif [[ "$ANSWER" == *NONE* ]]; then
      echo "NOT LOADED: $TARGET не грузится — годится под прогрессивное раскрытие"
    else
      echo "INCONCLUSIVE: неожиданный ответ «$ANSWER» — повторить вручную"; exit 2
    fi
    ;;
  *)
    sed -n '2,8p' "$0"
    exit 1
    ;;
esac
